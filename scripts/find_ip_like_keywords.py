lines.append(f"[IP 후보 키워드] ip_nodes_final 미등록 / 설명형 제외 — 총 {len(candidates)}개\n")
lines.append("=" * 70)

for kw, ips in candidates:
    lines.append(f"\n{kw}  ({len(ips)}개 IP에서 참조)")
    lines.append(f"  ← {', '.join(ips)}")

