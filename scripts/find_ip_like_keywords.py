# 한글 1~2글자 단어 제외 (너무 짧아 고유명사 아님)
def is_candidate(kw: str) -> bool:
    if kw in EXCLUDE:
        return False
    if re.fullmatch(r"[가-힣]{1,2}", kw):
        return False
    if re.fullmatch(r"[A-Za-z]{1,2}", kw):
        return False
    return True

